// Repetition is about a particular exercise/method, not just a similar title.
const seen = new Set();
export const schedule = days.map((entry, index) => ({
  day: index + 1,
  week: Math.floor(index / 7) + 1,
  title: entry.title,
  focus: entry.focus,
  blind: index >= 63,
  problems: entry.ids.map(id => {
    const revision = seen.has(id);
    seen.add(id);
    return { id, revision };
  }),
}));

// The daily renderer only receives the information appropriate to this week.
export function dayView(number) {
  const entry = schedule[number - 1];
  if (!entry) throw new RangeError('DSA day must be between 1 and 70.');
  return {
    day: entry.day, week: entry.week, title: entry.title, blind: entry.blind,
    focus: entry.blind ? '' : entry.focus,
    dpReminder: !entry.blind && entry.problems.some(item => {
      const taxonomy = patterns[problems[item.id].patternId];
      return taxonomy.category === 'Dynamic Programming' || taxonomy.dp;
    }),
    problems: entry.problems.map(item => {
      const source = problems[item.id];
      return {
        name: entry.blind ? (source.blindName || source.name) : source.name,
        revision: item.revision,
        activity: source.activity || false,
        ...(!entry.blind && { taxonomy: patterns[source.patternId] }),
      };
    }),
  };
}
